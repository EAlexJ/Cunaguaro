struct Decoder {
  static InstructionEnum decode(const reg_t instr) {
    for (const auto &entry : instructions) {
      if ((instr & entry.mask) == entry.value)
        return entry.instr;
    }
    throw rv_traps::Traps::Instruction_access_fault;
  }
};
